/*
 * Build config_templates.js from the files in templates/.
 *
 * The estimator page is opened directly from disk (file://) or from GitHub
 * Pages, and in both cases it cannot list a folder or read local files.
 * This script embeds every template file into config_templates.js, which
 * the page loads to fill the "Load a template" list.
 *
 * Run it again every time a template is added, changed or removed:
 *     node build_config_templates.js
 */
const fs   = require('fs');
const path = require('path');

const TEMPLATES_DIR = path.join(__dirname, 'templates');
const OUTPUT_FILE   = path.join(__dirname, 'config_templates.js');

const files = fs.readdirSync(TEMPLATES_DIR)
    .filter(f => /\.(txt|cfg)$/i.test(f))
    .sort((a, b) => a.localeCompare(b));

const templates = files.map(file => ({
    name: path.parse(file).name,    // file name without extension
    file,
    text: fs.readFileSync(path.join(TEMPLATES_DIR, file), 'utf8').replace(/\r\n/g, '\n'),
}));

const out =
`/*
 * AUTO-GENERATED by build_config_templates.js from the templates/ folder.
 * Do not edit by hand: change the files in templates/ and run
 *     node build_config_templates.js
 */
const CONFIG_TEMPLATES = ${JSON.stringify(templates, null, 4)};

if (typeof module !== 'undefined') module.exports = { CONFIG_TEMPLATES };
`;

fs.writeFileSync(OUTPUT_FILE, out);
console.log(`config_templates.js written with ${templates.length} template(s):`);
templates.forEach(t => console.log(`  - ${t.name}`));
